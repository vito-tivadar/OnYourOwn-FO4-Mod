#!/usr/bin/env python3
"""Old-gen build support (Fallout 4 1.10.163): Address Library ID headers and the ID check.

Usage:
  oldgen.py headers <dir>   writes <dir>/RE/IDs.h and <dir>/RE/IDs_VTABLE.h: CommonLibF4's headers
                            with the next-gen IDs from oldgen/ids.tsv replaced by old-gen IDs, and
                            <dir>/F4SE/Version.h with RUNTIME_LATEST = 1.10.163, the game version
                            F4SEPlugin_Version declares (mod managers read it)
  oldgen.py check <dll>     fails if the built DLL still uses a next-gen-only ID
"""

import argparse
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ID_HEADERS = ("IDs.h", "IDs_VTABLE.h")
HEADER_DIR = ROOT / "lib/commonlibf4/include/RE"
VERSION_HEADER = ROOT / "lib/commonlibf4/include/F4SE/Version.h"
NEXT_GEN_ONLY = 2_000_000  # the 1.10.163 Address Library has no IDs above this

ID_PATTERN = re.compile(r"(REL::ID\s+\w+\s*\{\s*|REL::ID\()(\d+)")


def load_map() -> dict[int, int]:
    ids = {}
    for line in (ROOT / "oldgen/ids.tsv").read_text().splitlines():
        if line and not line.startswith("#"):
            next_gen, old_gen, *_ = line.split("\t")
            ids[int(next_gen)] = int(old_gen)
    return ids


def header_ids() -> dict[int, str]:
    """Next-gen-only IDs in CommonLibF4's ID headers, with their names."""
    names = {}
    for header in ID_HEADERS:
        stack = []
        for line in (HEADER_DIR / header).read_text().splitlines():
            if m := re.match(r"\s*namespace ([\w:]+)", line):
                stack.append(m.group(1))
            elif re.match(r"\s*}", line) and stack:
                stack.pop()
            elif m := re.search(r"REL::ID\s+(\w+)\s*\{\s*(\d+)", line):
                names.setdefault(int(m.group(2)), "::".join(stack[1:] + [m.group(1)]))
            elif m := re.search(r"std::array<REL::ID, \d+>\s+(\w+)\{", line):
                for id in re.findall(r"REL::ID\((\d+)\)", line):
                    names.setdefault(int(id), "::".join(stack[1:] + [m.group(1)]))
    return {id: name for id, name in names.items() if id > NEXT_GEN_ONLY}


def write_headers(out_dir: Path) -> None:
    ids = load_map()
    unused = set(ids)
    (out_dir / "RE").mkdir(parents=True, exist_ok=True)
    for header in ID_HEADERS:
        def replace(m: re.Match) -> str:
            id = int(m.group(2))
            unused.discard(id)
            return m.group(1) + str(ids.get(id, id))

        text = ID_PATTERN.sub(replace, (HEADER_DIR / header).read_text())
        (out_dir / "RE" / header).write_text(f"// Generated by scripts/oldgen.py for Fallout 4 1.10.163.\n{text}")
    if unused:
        raise SystemExit(f"oldgen/ids.tsv lists IDs that CommonLibF4 no longer has: {sorted(unused)}")

    text, count = re.subn(r"(RUNTIME_LATEST\s*=\s*)RUNTIME_[\d_]+", r"\g<1>RUNTIME_1_10_163", VERSION_HEADER.read_text())
    if count != 1:
        raise SystemExit(f"no RUNTIME_LATEST in {VERSION_HEADER}")
    (out_dir / "F4SE").mkdir(parents=True, exist_ok=True)
    (out_dir / "F4SE/Version.h").write_text(f"// Generated by scripts/oldgen.py for Fallout 4 1.10.163.\n{text}")
    print(f"Wrote old-gen headers to {out_dir} ({len(ids)} IDs replaced, runtime 1.10.163)")


def used_ids(dll: Path, candidates: set[int]) -> set[int]:
    """Candidates the DLL loads as an instruction immediate or stores as 8-byte data."""
    data = dll.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    count, = struct.unpack_from("<H", data, pe + 6)
    optional_size, = struct.unpack_from("<H", data, pe + 20)
    found = set()
    for i in range(count):
        header = pe + 24 + optional_size + i * 40
        name = data[header:header + 8].rstrip(b"\0")
        raw_size, raw_offset = struct.unpack_from("<II", data, header + 16)
        section = data[raw_offset:raw_offset + raw_size]
        if name == b".text":
            # mov r32, imm32 (B8+r) or mov r/m, imm32 (C7 /0), the forms IDs are compiled into
            for at in range(8, len(section) - 4):
                value, = struct.unpack_from("<I", section, at)
                if value in candidates and (0xB8 <= section[at - 1] <= 0xBF or 0xC7 in section[at - 7:at - 1]):
                    found.add(value)
        elif name in (b".rdata", b".data"):
            found |= {v for (v,) in struct.iter_unpack("<Q", section[:len(section) // 8 * 8]) if v in candidates}
    return found


def check(dll: Path) -> None:
    names = header_ids()
    missing = used_ids(dll, set(names))
    if missing:
        listed = "\n".join(f"  {id}  {names[id]}" for id in sorted(missing))
        raise SystemExit(f"{dll} uses next-gen-only Address Library IDs; add their 1.10.163 IDs to oldgen/ids.tsv:\n{listed}")
    print(f"{dll}: no next-gen-only Address Library IDs")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("headers").add_argument("out_dir", type=Path)
    commands.add_parser("check").add_argument("dll", type=Path)
    args = parser.parse_args()
    if args.command == "headers":
        write_headers(args.out_dir)
    else:
        check(args.dll)


if __name__ == "__main__":
    main()
